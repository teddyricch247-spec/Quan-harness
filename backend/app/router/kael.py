"""Difficulty-router prompt for both Kael models (Kael Beta and Kael Pro Beta) —
added 2026-09-13.

Appended as a trailing `system` message on the DRAFT pass ONLY — never
the critic pass (see app/two_pass_pipeline.py's _draft_body(), the only
caller of build_router_message() in app/router/__init__.py; _critic_body()
has no equivalent call). This is a deliberate, load-bearing asymmetry: the
critic's entire job is reviewing an already-written draft, so instructing
it to also rate the difficulty of the ORIGINAL request is both irrelevant
to what it's doing and actively confusing framing to hand it (it never
sees the classification anyway — see below).

What this buys: on a genuinely trivial turn ("hello, who are you?"), the
current two-pass pipeline still runs a full second model call before
answering — real latency and real cost for a review pass that a trivial
greeting doesn't meaningfully benefit from. This prompt asks the draft
model to make one classification call BEFORE it starts actually
answering: is the task in front of it, by its own nature, the kind of
thing worth a second reviewer's attention, or not. app/two_pass_pipeline.py
reads that single word back out and either serves the draft directly
(EASY) or proceeds to the critic pass exactly as it always has (HARD) —
see two_pass_pipeline.py's own module docstring, "Difficulty routing"
section, for the orchestration side of this.

The tag itself (`{tag}` below, filled in with a fresh per-request
boundary the exact same way critic.build_critic_message()'s <draft_...>
wrapper already is — see that function's docstring for the full
tag-injection threat model this reuses) is stripped by
response_api.extract_difficulty_and_strip() BEFORE either downstream use:
before draft_text is ever computed for the critic prompt (so a HARD
rating's own tag can never leak into what the critic reviews), and before
an EASY rating's draft is ever reshaped into what the client receives (so
an EASY rating's own tag can never leak into output either). The critic
model never sees this instruction and never sees this tag — from its
perspective, this entire mechanism doesn't exist.

Trimmed ~25% (2,051 -> ~1,540 words) 2026-09-29: no category, rule, or
worked example was removed. The cut came from three places that were
saying the same thing more than once rather than saying something new
each time — "THE ONE THING THIS IS NOT" restated the confidence-vs-
correctness distinction across four synonymous negations before
explaining it, several HARD bullets restated their own justification
after already stating it, and two of the fourteen worked examples
("thanks, that's perfect" and "never mind, I'll figure it out myself")
illustrated the same "conversational close" case the EASY bullet above
them already lists by name — both phrases are still there, just as
quoted examples inside that bullet rather than as a second and third
standalone worked example for one category that already had one.
Stopped at ~25%, short of a flatter 30%, once further cuts stopped being
repetition and started being the WHY-arithmetic-is-a-documented-weak-
point reasoning, the WHY-confidence-is-unreliable reasoning, or another
actual HARD category or worked example — the same content/length
tradeoff CRITIC_PROMPT's own rewrite above draws a line on, applied here.
"""

ROUTER_PROMPT = """Before you write anything else, produce one structured internal classification: how difficult is the task in front of you, considered strictly on its own terms? This is separate from your actual response — a self-contained analytical judgment, not a preamble or summary of what follows, connected to it only by being part of the same output. Give it real, careful thought, not a reflexive guess.

THE ONE THING THIS IS NOT, SAID AS PLAINLY AS POSSIBLE:

This is not a rating of how well you think you just did — not a confidence score, not "how sure am I this is correct." That question is about YOUR OUTPUT. This classification is about the REQUEST itself, independent of and prior to whatever you go on to write in response to it.

That distinction matters because a model can be completely fluent, confident-sounding, and wrong, all at once. Feeling sure is just a feeling, generated by the same process that produced the possibly-wrong answer — exactly as unreliable as that process is. Rate difficulty by your own confidence and you will systematically call hard things easy in precisely the cases where you're confidently wrong about them — the one case this classification most needs to catch.

So ask a different question, one that never mentions your own answer: "Setting aside how I feel about what I just wrote — by its own nature, is THIS REQUEST the kind of task where a careful, independent reviewer, with no stake in defending the answer and no memory of writing it, would have a realistic chance of finding something wrong, missing, or handled worse than it should have been?"

WHAT MAKES A TASK EASY:

A task is easy when it's short, low-stakes, and low-ambiguity enough that there's essentially no realistic room for a subtle, non-obvious mistake to exist in it at all. Properties that point toward easy:

- Purely conversational or social turns with no informational content to get wrong: greetings, small talk, thanks, acknowledgments, "how are you," "who are you," "ok sounds good," goodbyes, "never mind."
- Simple, single-fact lookups with a short, objectively correct, universally agreed answer, where the whole task is retrieving one static fact rather than reasoning, and a wrong answer would be an obvious, low-stakes slip — "what's the capital of France," "who wrote Romeo and Juliet."
- Trivial rewrites or formatting changes with one unambiguous instruction and small output: fixing one obvious typo, making one short sentence slightly more formal.
- Single-digit or otherwise genuinely trivial arithmetic that needs no carrying, no multi-step computation, nothing you'd need to double check — "what's 2 plus 2," "what's half of 10."
- Short, single-turn, single-step requests with exactly one reasonable interpretation, no sub-parts to track, no domain expertise required, and an answer short enough that a mistake, if there were one, would be immediately obvious rather than subtle.

If a task satisfies essentially all of the above — nothing to reason through, nothing ambiguous, nothing where a wrong answer would be non-obvious — it's easy.

WHAT MAKES A TASK HARD:

A task is hard whenever ANY of the following is true. This list is deliberately broader and given more weight than the easy list — intentional, not an oversight, for the reason given in the tie-breaker section below.

- Any code: writing it, modifying it, debugging it, explaining it, reviewing it. One of the clearest hard categories there is — subtle bugs and silently-wrong logic are exactly what a fluent, confident-sounding answer can contain without that being apparent from one read.
- An open-ended build/create/design request for something substantial — an app, a game, a script, a tool, a document, a plan, a multi-file project — even phrased casually or as a joke ("build me GTA 6 in a single HTML file"). Scope and ambition are their own difficulty signal, independent of how the request is worded.
- Multiple distinct sub-requirements that all need to be individually satisfied — numbered lists, "do X and also make sure Y and don't forget Z." Fluent prose can silently drop or half-answer one part while still sounding complete, unlike a missing line of code.
- Several sequential reasoning steps where an early error would silently propagate — math word problems, logic puzzles, riddles, multi-step planning, "if X then Y then given Z what happens."
- A precise, exactly-checkable answer that's nonetheless non-trivial to compute reliably — multi-digit or multi-step arithmetic, exact counting, date/time arithmetic, multi-step unit conversions. These are documented model weak points: tasks that look simple but that get it wrong more often than the question's surface difficulty suggests. Treat that pattern itself as a hard signal, on top of how complicated the task looks.
- Creative writing with real length or substance — stories, essays, scripts, marketing copy — anywhere tone, coherence, and quality genuinely vary and a flaw might not be obvious on a first read, unlike a one-line rewrite.
- A specific structured output format to hit exactly — JSON matching a schema, a particular file format, strict adherence to a template or style guide. Precise-format tasks are exactly where an answer can get 95% of the structure right while silently violating one constraint.
- Any factual claim where being wrong could actually mislead someone who acts on it — medical, legal, financial, safety-related, or otherwise consequential, even if it doesn't feel computationally "hard." Stakes are their own difficulty axis, separate from complexity.
- Tracking or synthesizing a meaningful amount of context — long documents, multiple files, accumulated multi-turn state, several constraints that all have to stay consistent with each other.
- Making several non-obvious judgment calls to produce an answer — filling in unstated assumptions, picking among plausible interpretations, resolving an ambiguity the request left open. Real decisions required at all make the task hard by definition.
- Anything you're simply not sure how to classify.

THE TIE-BREAKER, WHICH IS NOT REALLY A TIE-BREAKER:

If a task has any real mix of easy-leaning and hard-leaning properties, or you're genuinely unsure which applies, classify it hard. This is a deliberately asymmetric default: the two mistakes here aren't equally costly. Calling something easy when it genuinely wasn't is the more expensive error, categorically — overstating difficulty has no comparable downside. "I'm not sure" always resolves to hard.

OUTPUT FORMAT — FOLLOW THIS EXACTLY:

The very first thing in your response, before any greeting, before any preamble, before the first word of your actual answer, must be:

<{tag}>
WORD
</{tag}>

— where WORD is exactly one of these two words, spelled and capitalized exactly like this, and nothing else: EASY or HARD.

Put nothing else inside those tags — no punctuation, explanation, both words, or different capitalization — only the bare word EASY or HARD, exactly as shown. You may reason about which one applies as part of your own normal reasoning process before you output anything — that reasoning never needs to appear inside these tags, or anywhere in your visible answer at all.

Immediately after the closing tag, continue directly into your actual, complete answer — no gap, no meta-commentary, nothing that would tip the person off this classification ever happened. Answer exactly as you would if this instruction didn't exist, except for the one tag at the very top.

WORKED EXAMPLES:

"hello, who are you?" -> EASY. Purely conversational, no informational content that could be wrong.

"what's the capital of Japan?" -> EASY. Single static fact, universally agreed, trivially checkable, low stakes if somehow wrong.

"can you make this sentence a bit more formal: 'hey can we push the meeting'" -> EASY. One short, unambiguous rewrite instruction, tiny output, an error would be immediately obvious on sight.

"what's 6 times 7?" -> EASY. Trivial, single-step, memorizable arithmetic.

"build me GTA 6 in a single html file" -> HARD. Open-ended, substantial build request — scope alone makes this hard regardless of tone.

"write a Python function that merges two sorted linked lists" -> HARD. Code: exactly the category where a subtle off-by-one or edge-case bug is likely and not obviously visible on a casual read.

"what's 4,739 times 82?" -> HARD, even though it "is just multiplication." Multi-digit arithmetic is a documented model weak spot and has a single, exactly-checkable correct answer worth verifying.

"summarize this contract and tell me if the termination clause is standard" -> HARD. Consequential if wrong (legal/financial stakes) and requires synthesizing real content, not retrieving a static fact.

"write a 600-word blog post about the future of remote work" -> HARD. Substantial creative/persuasive writing where careful attention to tone, coherence, and structure has real value, and where a flaw might not be obvious on a first read.

"here's my JSON schema, generate 5 example objects that validate against it" -> HARD. Precise structured-output task — exactly where an answer can silently violate one field of the schema while looking correct overall.

"can you rename this variable from `x` to `userCount` in this file, that's the only change" -> HARD, even though it sounds small, because it's code — a seemingly one-line change is still where an easy-to-miss second occurrence of `x` (a different scope, a comment, a string) is a realistic mistake.

"I'm planning a 3-day trip to Kyoto, can you build me an itinerary with a mix of temples, food, and one day trip out of the city?" -> HARD. Multi-part, needs several constraints (3 days, temples, food, a day trip) to all stay consistent and non-redundant at once."""
