"""
Phase 6.1 (§17, step 19) — pictures attached to user messages. See db/migrations/0013_session_attachments.sql
and app/services/image_input.py for the whole design; this is only the storage half.

Same scoping rule as every other repository here: this module uses the service-role client, which bypasses RLS,
so NOTHING in it is "already authorized" — every function takes `session_id`, and every caller has just verified
that session belongs to the signed-in user (`sessions_repo.get_owned`). Every query below is filtered by
`session_id`, so an attachment id from another session (or another account) simply matches nothing: claiming it
returns no row, loading it returns no data.

The data column (base64 text, up to ~4 MB) is only ever read by `load_data_uris` — every listing and every state
change returns metadata only (the three transitions are SQL functions for exactly that reason).
"""
import datetime
import secrets
import uuid

from starlette.concurrency import run_in_threadpool

from app.db import get_service_client
from app.services import image_input

TABLE = "session_attachments"
META_COLUMNS = "id,session_id,filename,media_type,width,height,byte_size,message_event_id,created_at"


def _all_uuids(values: list[str]) -> bool:
    """A malformed id must read as "not available", not reach Postgres as a cast error (a 500)."""
    try:
        for value in values:
            uuid.UUID(str(value))
    except ValueError:
        return False
    return True


def new_claim_token() -> int:
    """A unique NEGATIVE bigint marking 'claimed by a message that is being written' (a real event id is positive)."""
    return -(secrets.randbelow(2**62) + 1)


def event_metadata(row: dict) -> dict:
    """The only attachment fields that ever go into a session_events row."""
    return {
        "id": row["id"],
        "filename": row["filename"],
        "media_type": row["media_type"],
        "width": row["width"],
        "height": row["height"],
        "byte_size": row["byte_size"],
    }


async def create(
    session_id: str, *, attachment_id: str, filename: str, media_type: str, width: int, height: int, byte_size: int, data_b64: str
) -> None:
    """`attachment_id` is generated by the caller (a uuid4) so nothing has to be read back."""
    client = get_service_client()

    def _call():
        client.table(TABLE).insert(
            {
                "id": attachment_id,
                "session_id": session_id,
                "filename": filename,
                "media_type": media_type,
                "width": width,
                "height": height,
                "byte_size": byte_size,
                "data_b64": data_b64,
            }
        ).execute()

    await run_in_threadpool(_call)


async def count_pending(session_id: str) -> int:
    """Uploaded but not yet attached to a message (the per-session quota)."""
    client = get_service_client()

    def _call():
        result = client.table(TABLE).select("id", count="exact").eq("session_id", session_id).is_("message_event_id", "null").execute()
        return result.count if result.count is not None else len(result.data)

    return await run_in_threadpool(_call)


async def purge_stale(session_id: str) -> None:
    """Deletes this session's uploads that were never attached (NULL) or whose message never got written (a
    claim token, negative), once they're older than image_input.STALE_PENDING_SECONDS. Called opportunistically at
    upload time — no background task."""
    cutoff = (datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(seconds=image_input.STALE_PENDING_SECONDS)).isoformat()
    client = get_service_client()

    def _call():
        client.table(TABLE).delete().eq("session_id", session_id).lt("created_at", cutoff).or_(
            "message_event_id.is.null,message_event_id.lt.0"
        ).execute()

    await run_in_threadpool(_call)


async def claim_unlinked(session_id: str, attachment_ids: list[str], token: int) -> list[dict] | None:
    """Atomically take ownership of `attachment_ids` for the message about to be written. Returns their metadata
    IN THE ORDER REQUESTED, or None — and takes nothing — unless every id is in this session and still unattached
    (a missing, foreign, duplicated or already-used id all look the same: not available)."""
    if len(set(attachment_ids)) != len(attachment_ids) or not _all_uuids(attachment_ids):
        return None
    client = get_service_client()

    def _call():
        return client.rpc(
            "claim_session_attachments", {"p_session_id": session_id, "p_ids": attachment_ids, "p_token": token}
        ).execute().data

    rows = await run_in_threadpool(_call)
    if len(rows) != len(attachment_ids):
        if rows:
            await release(session_id, token)  # a partial claim is no claim
        return None
    order = {attachment_id: i for i, attachment_id in enumerate(attachment_ids)}
    return sorted(rows, key=lambda r: order[r["id"]])


async def link(session_id: str, token: int, event_id: int) -> None:
    client = get_service_client()

    def _call():
        client.rpc("link_session_attachments", {"p_session_id": session_id, "p_token": token, "p_event_id": event_id}).execute()

    await run_in_threadpool(_call)


async def release(session_id: str, token: int) -> None:
    """Gives claimed attachments back (the message they were claimed for was never written)."""
    client = get_service_client()

    def _call():
        client.rpc("release_session_attachments", {"p_session_id": session_id, "p_token": token}).execute()

    await run_in_threadpool(_call)


async def load_data_uris(session_id: str, attachment_ids: list[str]) -> dict[str, str]:
    """{attachment id: "data:<type>;base64,<data>"} for the ids that exist in this session — the only function
    that reads the pixels. An id that isn't found is simply absent from the result (message_builder then names it
    in a note instead)."""
    if not attachment_ids:
        return {}
    client = get_service_client()

    def _call():
        return client.table(TABLE).select("id,media_type,data_b64").eq("session_id", session_id).in_("id", attachment_ids).execute().data

    rows = await run_in_threadpool(_call)
    return {r["id"]: f"data:{r['media_type']};base64,{r['data_b64']}" for r in rows}


async def get_data(session_id: str, attachment_id: str) -> dict | None:
    """One picture's {media_type, data_b64}, or None if it isn't in this session (GET /sessions/{id}/attachments/{id})."""
    if not _all_uuids([attachment_id]):
        return None
    client = get_service_client()

    def _call():
        return client.table(TABLE).select("media_type,data_b64").eq("session_id", session_id).eq("id", attachment_id).limit(1).execute().data

    rows = await run_in_threadpool(_call)
    return rows[0] if rows else None
